#!/usr/bin/env python3
"""Produce one exact box-separated infeasibility certificate when scheduled.

This file is not a proof of the projection's geometric premises. It rebuilds
one status-2 receipt using frozen degree19_projection_v3.py, solves a numerical
phase-one LP, and checks the rounded row combination with Python integers.
An exact negative gap concerns that rebuilt model, even if the input receipt
was generated by an older projection source. No batch mode is provided.

Example, to be run only when the parent research task schedules this case:
  python3 degree19_phaseone.py --receipt degree19/Zpattern03-none.json

The compute deadline includes imports, model construction, solving and integer
checking. The solver also receives only the remaining part of at most 30 s.
"""

import argparse
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import re
import signal
import sys
import time

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
FROZEN_MODEL = HERE / "degree19_projection_v3.py"
SCALE = 10**10


class DeadlineExceeded(TimeoutError):
    pass


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def exact_integer(value, context):
    """Reject a nonintegral model value rather than silently truncate it."""
    if value is None or not math.isfinite(float(value)):
        raise ValueError(f"{context}: expected a finite integer, got {value!r}")
    result = int(value)
    if value != result:
        raise ValueError(f"{context}: nonintegral value {value!r}")
    return result


def equality_labels(model):
    """Record the frozen build() order: one normalization and seven features."""
    from itertools import combinations

    result = []
    for triple in model.LINK:
        points = [v for v in range(12) if triple >> v & 1]
        features = [model.mask(pair) for pair in combinations(points, 2)]
        features += [triple] + [1 << v for v in points]
        result.append(["local-normalization", triple])
        result.extend(["local-feature", triple, feature] for feature in features)
    return result


def produce(receipt_path, seconds):
    start = time.monotonic()
    deadline = start + seconds
    record = {
        "assurance": "exact arithmetic diagnostic under the rebuilt model's original premises; not Lean or a complete mathematical proof",
        "phase_one_status": "started",
        "compute_limit_seconds": seconds,
        "receipt_path": str(receipt_path),
        "receipt_sha256": digest(receipt_path),
        "producer_sha256": digest(__file__),
        "rebuilt_source_path": str(FROZEN_MODEL),
        "rebuilt_source_sha256": digest(FROZEN_MODEL),
        "scale": SCALE,
    }

    def remaining():
        value = deadline - time.monotonic()
        if value <= 0:
            raise DeadlineExceeded("The phase-one compute deadline expired")
        return value

    def alarm_handler(_signum, _frame):
        raise DeadlineExceeded("The phase-one compute deadline expired")

    old_handler = signal.signal(signal.SIGALRM, alarm_handler)
    signal.setitimer(signal.ITIMER_REAL, max(0.001, deadline - time.monotonic()))
    try:
        receipt = json.loads(receipt_path.read_text())
        if receipt.get("status") != 2:
            raise ValueError("--receipt must identify exactly one numerical status-2 case")
        record["original_receipt_status"] = 2
        record["original_source_sha256"] = receipt.get("source_sha256")
        record["receipt_source_matches_rebuild"] = (
            receipt.get("source_sha256") == record["rebuilt_source_sha256"]
        )
        record["original_premise_metadata"] = {
            key: receipt.get(key)
            for key in ("target_residuals", "mu", "point_cap", "assurance")
        }
        case = receipt["case"]
        empty = receipt.get("empty", "none")
        assigned = receipt.get("assigned")
        forbidden = receipt.get("forbidden", [])
        record.update(case=case, empty=empty, assigned=assigned, forbidden=forbidden)

        # Explicit file loading avoids accidentally importing the mutable base.
        spec = importlib.util.spec_from_file_location("degree19_frozen_v3", FROZEN_MODEL)
        if spec is None or spec.loader is None:
            raise ImportError(f"Cannot load frozen projection: {FROZEN_MODEL}")
        model = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(model)
        import numpy as np
        import scipy
        from scipy.optimize import linprog
        from scipy.sparse import csr_matrix, hstack, vstack

        record["source_dependencies"] = {
            "imported_local43_path": str(Path(model.L.__file__).resolve()),
            "imported_local43_sha256": digest(model.L.__file__),
            "orbit_catalogue_sha256": digest(model.SOURCE / "D19/data/ORBIT_CATALOGUE.json"),
        }
        record["versions"] = {"python": sys.version, "numpy": np.__version__, "scipy": scipy.__version__}
        if case not in model.MARKERS:
            raise ValueError(f"Unknown marker case: {case!r}")
        if empty not in ("none", "Y", "Z", "both"):
            raise ValueError(f"Unknown empty-component option: {empty!r}")
        if assigned is not None and (not isinstance(assigned, dict) or set(assigned) - {"Y", "Z"}):
            raise ValueError("Assigned components must be a mapping using only Y and Z")
        remaining()
        traces, bounds, A, b, E, f, labels, sizes = model.build(case, empty, assigned, forbidden)
        remaining()
        A, E = A.tocsr(), E.tocsr()
        columns = len(bounds)
        eq_labels = equality_labels(model)
        if A.shape != (len(b), columns) or E.shape != (len(f), columns):
            raise ValueError("The rebuilt matrix dimensions do not match its bounds")
        if len(labels) != len(b) or len(eq_labels) != len(f):
            raise ValueError("The frozen row ordering does not match its label metadata")
        integer_bounds = [
            (exact_integer(lo, f"lower bound {j}"), exact_integer(hi, f"upper bound {j}"))
            for j, (lo, hi) in enumerate(bounds)
        ]
        if any(lo > hi for lo, hi in integer_bounds):
            raise ValueError("Conflicting original box bounds")
        record["model"] = {
            "trace_columns": len(traces), "original_columns": columns,
            "inequality_rows": len(b), "equality_rows": len(f),
            "catalogue_sizes": sizes,
            "receipt_columns_match_rebuild": receipt.get("columns") == columns,
        }
        record["phase_one_formulation"] = {
            "objective": "minimize t",
            "original_box_bounds": "unchanged",
            "slack_bound": [0, None],
            "assembled_row_order": ["A x - t <= b", "E x - t <= f", "-E x - t <= -f"],
            "equality_positive_sign": 1,
            "equality_negative_sign": -1,
        }
        stacked = vstack((A, E, -E), format="csr")
        slack_column = csr_matrix(-np.ones((stacked.shape[0], 1)))
        phase_matrix = hstack((stacked, slack_column), format="csr")
        phase_rhs = np.concatenate((b, f, -f))
        objective = np.zeros(columns + 1)
        objective[-1] = 1
        time_left = remaining()
        result = linprog(
            objective, A_ub=phase_matrix, b_ub=phase_rhs,
            bounds=bounds + [(0, None)], method="highs",
            options={"time_limit": time_left},
        )
        record["solver"] = {
            "status": int(result.status), "message": str(result.message),
            "phase_one_minimum": None if result.fun is None else float(result.fun),
            "solver_time_limit_seconds": time_left,
        }
        remaining()
        if result.status != 0:
            record["phase_one_status"] = "solver-did-not-complete"
            return record

        raw = [-float(value) for value in result.ineqlin.marginals]
        if len(raw) != len(b) + 2 * len(f) or not all(math.isfinite(value) for value in raw):
            raise ValueError("Missing or nonfinite phase-one inequality marginals")
        weights = [max(0, round(value * SCALE)) for value in raw]
        a_weights = weights[:len(b)]
        e_positive = weights[len(b):len(b) + len(f)]
        e_negative = weights[len(b) + len(f):]
        e_signed = [positive - negative for positive, negative in zip(e_positive, e_negative)]
        record["weights"] = {
            "conversion": "max(0, round(-ineqlin.marginal * 10^10)); Python nearest-even rounding",
            "zero_entries": "included explicitly in all three nonnegative weight arrays",
            "inequality": a_weights, "equality_positive": e_positive,
            "equality_negative": e_negative, "equality_signed": e_signed,
            "inequality_labels": labels, "equality_labels": eq_labels,
            "minimum_unrounded_nonnegative_candidate": min(raw, default=0.0),
            "clamped_negative_candidates": sum(value < 0 for value in raw),
            "slack_column_coefficient": -sum(weights),
        }

        # Ignore the phase-one slack column now. Each original row is valid
        # at t=0; nonnegative weights imply q.x <= H in the original model.
        q = [0] * columns
        H = 0
        for matrix, rhs, row_weights in ((A, b, a_weights), (E, f, e_signed)):
            for i, weight in enumerate(row_weights):
                if not weight:
                    continue
                H += weight * exact_integer(rhs[i], f"row RHS {i}")
                for k in range(matrix.indptr[i], matrix.indptr[i + 1]):
                    j = int(matrix.indices[k])
                    q[j] += weight * exact_integer(matrix.data[k], f"matrix coefficient ({i},{j})")
                if i % 32 == 0:
                    remaining()
        box_minimum = sum(min(lo * value, hi * value) for (lo, hi), value in zip(integer_bounds, q))
        gap = H - box_minimum
        coefficient_hash = hashlib.sha256()
        for value in q:
            coefficient_hash.update((str(value) + "\n").encode())
        record["exact_check"] = {
            "H": H,
            "box_minimum": box_minimum,
            "G": gap,
            "formula": "G = H - sum_j min(l_j*q_j, u_j*q_j), over every original column",
            "q_definition": "A^T*y_A + E^T*(y_E_positive-y_E_negative)",
            "q_column_count": columns,
            "q_sha256_decimal_lines": coefficient_hash.hexdigest(),
            "all_source_row_weights_nonnegative": all(weight >= 0 for weight in weights),
            "strict_negative_gap": gap < 0,
            "interpretation": (
                "The exact weighted inequality contradicts the original box bounds of the rebuilt v3 model."
                if gap < 0 else
                "These rounded weights do not certify infeasibility; no contradiction is claimed."
            ),
        }
        remaining()
        record["phase_one_status"] = "exact-negative-gap" if gap < 0 else "no-exact-negative-gap"
        return record
    except DeadlineExceeded as exc:
        record["phase_one_status"] = "compute-timeout"
        record["error"] = str(exc)
        return record
    except Exception as exc:
        record["phase_one_status"] = "error"
        record["error"] = f"{type(exc).__name__}: {exc}"
        return record
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        signal.signal(signal.SIGALRM, old_handler)
        record["compute_seconds"] = time.monotonic() - start


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--receipt", type=Path, required=True, help="One existing D19 status-2 JSON receipt")
    parser.add_argument("--seconds", type=float, default=30, help="Whole-computation deadline, at most 30 seconds")
    parser.add_argument("--label", help="Output label; defaults to the input receipt stem")
    args = parser.parse_args()
    if not 0 < args.seconds <= 30:
        parser.error("--seconds must be positive and at most 30")
    receipt_path = args.receipt.resolve()
    if not receipt_path.is_file():
        parser.error("--receipt must be an existing file")
    label = args.label or receipt_path.stem
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", label):
        parser.error("--label must be a simple filename label")
    record = produce(receipt_path, args.seconds)
    record["receipt_label"] = label
    output = HERE / "degree19" / (label + "-phaseone.json")
    output.parent.mkdir(exist_ok=True)
    temporary = output.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(record, indent=2, allow_nan=False) + "\n")
    temporary.replace(output)
    print(json.dumps({
        "output": str(output), "status": record["phase_one_status"],
        "exact_negative_gap": record.get("exact_check", {}).get("strict_negative_gap", False),
        "G": record.get("exact_check", {}).get("G"),
        "seconds": record["compute_seconds"],
    }), flush=True)
    return 0 if record["phase_one_status"] == "exact-negative-gap" else 1


if __name__ == "__main__":
    raise SystemExit(main())
